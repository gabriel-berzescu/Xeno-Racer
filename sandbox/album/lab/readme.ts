// Reads the album README and the source files it embeds, regenerates its tables, and generates the typed file that holds all of its
// runnable code (used by tests/probes/album-docs.test.ts to rewrite them, and by tests/album-engine.test.ts to check that they are up
// to date and to run the code). Files are read with LF line endings whatever the checkout used.
import { readFileSync, writeFileSync } from 'node:fs';
import { CATALOG, FX_CATALOG, fillReadme, type ReadmeSources } from '../../../src/audio/album/catalog';

export const README_URL = new URL('../../../src/audio/album/README.md', import.meta.url);
export const SNIPPETS_URL = new URL('../readme-snippets.ts', import.meta.url);

const lf = (s: string): string => s.replace(/\r\n/g, '\n');

export function readmeSources(): ReadmeSources {
  // the examples live in sandbox/album/ and are shown as they would be written in tracks/: one level above the engine's song.ts
  const read = (rel: string): string => lf(readFileSync(new URL(rel, import.meta.url), 'utf8')).replace("'../../src/audio/album/song'", "'../song'");
  return { example: read('../example-track.ts'), custom: read('../custom-instrument.ts'), script: read('./script-example.ts') };
}

export function readReadme(): string {
  return lf(readFileSync(README_URL, 'utf8'));
}

/** The README with every generated block brought up to date. */
export function renderReadme(): string {
  return fillReadme(readReadme(), readmeSources());
}

export function writeReadme(text: string): void {
  writeFileSync(README_URL, text);
}

const indent = (code: string, n: number): string =>
  code
    .split('\n')
    .map((l) => (l.length ? ' '.repeat(n) + l : l))
    .join('\n');

/**
 * Every `ts run` block of the README, in order, plus the example of each instrument of the catalogue, as the body of one typed
 * function: the project's normal `tsc --noEmit` type-checks the guide's code, and the tests run it.
 */
export function renderSnippets(readme: string): string {
  const blocks = [...readme.matchAll(/```ts run\n([\s\S]*?)```/g)].map((m) => m[1].trimEnd());
  const body: string[] = [];
  blocks.forEach((b, i) => body.push(`  mark(${i + 1});`, indent(b, 2), ''));
  CATALOG.forEach((d, i) => body.push(`  mark(${blocks.length + i + 1}); // example: s.${d.factory}`, '  {', indent(d.example, 4), '  }', ''));
  FX_CATALOG.forEach((d, i) => body.push(`  mark(${blocks.length + CATALOG.length + i + 1}); // example: fx.${d.name}`, '  {', indent(d.example, 4), '  }', ''));
  return `// GENERATED by \`DOCS=1 npx vitest run tests/probes/album-docs.test.ts\` from the \`ts run\` blocks of src/audio/album/README.md and the
// examples of src/audio/album/catalog.ts. Do not edit: change the README or the catalogue and regenerate. The project's type check
// (\`npx tsc --noEmit\`) checks this code, tests/album-engine.test.ts runs it.
import { fx, guitarChord } from '../../src/audio/album/song';
import type { Section, Song, SynthOpts } from '../../src/audio/album/song';

/** The song and the channels the README's code blocks work with (the guide says "given the channels of the worked example"). */
export interface ReadmePrelude {
  s: Song;
  S: { intro: Section; verse: Section; drop: Section; outro: Section };
  kick: ReturnType<Song['kick']>;
  kit: ReturnType<Song['drumKit']>;
  bass: ReturnType<Song['darkBass']>;
  pad: ReturnType<Song['synth']>;
  stab: ReturnType<Song['synth']>;
  arp: ReturnType<Song['synth']>;
  lead: ReturnType<Song['synth']>;
  riser: ReturnType<Song['riser']>;
  gtr: ReturnType<Song['guitar']>;
}

export function readmeSnippets(p: ReadmePrelude, mark: (block: number) => void): void {
  const { s, S, kick, kit, bass, pad, stab, arp, lead, riser, gtr } = p;
  void [fx, guitarChord, kick, kit, bass, pad, stab, arp, lead, riser, gtr, S, s];
  void (null as SynthOpts | null);

${body.join('\n')}
}

export const SNIPPET_BLOCKS = ${blocks.length};
export const EXAMPLE_BLOCKS = ${CATALOG.length + FX_CATALOG.length};
`;
}

export function readSnippets(): string {
  try {
    return lf(readFileSync(SNIPPETS_URL, 'utf8'));
  } catch {
    return '';
  }
}

export function writeSnippets(text: string): void {
  writeFileSync(SNIPPETS_URL, text);
}
